import { expect, it } from 'vitest';
import { createMockupRequest, generateMockup, type MockupProvider } from '../../src/mockups/providers';
import { resolveMockupPrompt } from '../../src/mockups/prompts';

it('does not claim generation when no provider is configured', async () => {
  const request = createMockupRequest(resolveMockupPrompt('laptop', { mode: 'scene' }));
  await expect(generateMockup(request)).rejects.toThrow(/provedor/i);
});

it('will not send missing input prompts for generation', () => {
  expect(() => createMockupRequest(resolveMockupPrompt('laptop', {}))).toThrow(/incompleto/i);
});

it('returns generated bytes with request provenance and pending review without a document mutation', async () => {
  const request = createMockupRequest(resolveMockupPrompt('laptop', { mode: 'scene' }));
  const original = structuredClone(request);
  const provider: MockupProvider = {
    id: 'test-adapter', name: 'Test adapter',
    async generate(input) {
      return { image: new Blob(['real adapter bytes'], { type: 'image/png' }), model: 'explicit-model', kind: input.output, provenance: { ...input, providerId: 'test-adapter', generatedAt: '2026-10-15T00:00:00.000Z' }, review: 'approved' };
    },
  };
  const result = await generateMockup(request, provider);
  expect(await result.image.text()).toBe('real adapter bytes');
  expect(result.provenance.prompt).toContain('laptop');
  expect(result.provenance.assetIds).toEqual([]);
  expect(result.provenance.providerId).toBe('test-adapter');
  expect(result.review).toBe('pending');
  expect(request).toEqual(original);
});

it('rejects empty/non-image provider results and exposes adapter failures', async () => {
  const request = createMockupRequest(resolveMockupPrompt('laptop', { mode: 'scene' }));
  const empty: MockupProvider = { id: 'empty', name: 'Empty', async generate(input) {
    return { image: new Blob([]), model: 'model', kind: input.output, provenance: { ...input, providerId: 'empty', generatedAt: '2026-10-15T00:00:00.000Z' }, review: 'pending' };
  } };
  await expect(generateMockup(request, empty)).rejects.toThrow(/imagem/i);
  const failing: MockupProvider = { id: 'failure', name: 'Failure', async generate() { throw new Error('Quota exceeded'); } };
  await expect(generateMockup(request, failing)).rejects.toThrow('Quota exceeded');
});
